'use strict';

require('dotenv').config();

const fs = require('fs');
const path = require('path');
const Database = require('better-sqlite3');
const { Pool } = require('pg');
const { createPostgresConfig, validatePostgresConfig } = require('../database/providers');
const { translatePostgresSql } = require('../database/sqlCompatibility');

const force = process.argv.includes('--force');

function quoteIdentifier(value) {
  return `"${String(value).toLowerCase().replace(/"/g, '""')}"`;
}

function resolveSqlitePath() {
  const configured = String(process.env.SQLITE_SOURCE_PATH || process.env.DB_PATH || '').trim();
  if (configured) {
    if (!fs.existsSync(configured)) throw new Error(`SQLite source database is unavailable: ${configured}`);
    return configured;
  }

  const candidates = [
    'Z:\\database.db',
    '\\\\PC-SERVER\\Database\\database.db',
    path.resolve(__dirname, '..', 'database.db')
  ];
  const found = candidates.find((candidate) => fs.existsSync(candidate));
  if (!found) throw new Error(`SQLite source database was not found. Checked: ${candidates.join(', ')}`);
  return found;
}

function postgresType(sqliteType) {
  const type = String(sqliteType || '').toUpperCase();
  if (type.includes('INT')) return 'BIGINT';
  if (type.includes('BLOB')) return 'BYTEA';
  if (type.includes('REAL') || type.includes('FLOA') || type.includes('DOUB')) return 'DOUBLE PRECISION';
  if (type.includes('NUM') || type.includes('DEC')) return 'NUMERIC';
  if (type.includes('BOOL')) return 'BOOLEAN';
  return 'TEXT';
}

function postgresDefault(value) {
  if (value === null || value === undefined) return '';
  const sql = String(value).trim();
  if (/^(NULL|CURRENT_DATE|CURRENT_TIME|CURRENT_TIMESTAMP|[-+]?\d+(?:\.\d+)?|'(?:[^']|'')*')$/i.test(sql)) {
    return ` DEFAULT ${sql}`;
  }
  if (/^"(?:[^"]|"")*"$/.test(sql)) {
    return ` DEFAULT '${sql.slice(1, -1).replace(/''/g, "''''").replace(/""/g, '"')}'`;
  }
  return '';
}

function columnType(sqlite, tableName, column) {
  const declaredType = postgresType(column.type);
  if (declaredType !== 'BIGINT' && declaredType !== 'DOUBLE PRECISION' && declaredType !== 'NUMERIC') {
    return declaredType;
  }

  const incompatible = sqlite.prepare(`
    SELECT 1
    FROM ${quoteIdentifier(tableName)}
    WHERE ${quoteIdentifier(column.name)} IS NOT NULL
      AND typeof(${quoteIdentifier(column.name)}) NOT IN ('integer', 'real')
    LIMIT 1
  `).get();
  return incompatible ? 'TEXT' : declaredType;
}

function tableDefinition(sqlite, tableName) {
  const columns = sqlite.prepare(`PRAGMA table_info(${quoteIdentifier(tableName)})`).all();
  const primaryColumns = columns.filter((column) => column.pk).sort((left, right) => left.pk - right.pk);
  const singleIntegerPrimaryKey = primaryColumns.length === 1
    && columnType(sqlite, tableName, primaryColumns[0]) === 'BIGINT';
  const definitions = columns.map((column) => {
    const type = columnType(sqlite, tableName, column);
    const primary = singleIntegerPrimaryKey && column.pk
      ? ' GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
      : '';
    const required = column.notnull && !primary ? ' NOT NULL' : '';
    return `${quoteIdentifier(column.name)} ${type}${primary}${required}${postgresDefault(column.dflt_value)}`;
  });

  if (primaryColumns.length && !singleIntegerPrimaryKey) {
    definitions.push(`PRIMARY KEY (${primaryColumns.map((column) => quoteIdentifier(column.name)).join(', ')})`);
  }

  return { columns, sql: `CREATE TABLE ${quoteIdentifier(tableName)} (${definitions.join(', ')})` };
}

async function targetTableExists(client, tableName) {
  const exists = await client.query('SELECT to_regclass($1) AS name', [`public.${tableName.toLowerCase()}`]);
  return Boolean(exists.rows[0]?.name);
}

async function copyTable(client, sqlite, tableName, columns) {
  if (!columns.length) return 0;
  const names = columns.map((column) => column.name);
  const statement = sqlite.prepare(`SELECT * FROM ${quoteIdentifier(tableName)}`);
  const batchSize = Math.max(1, Math.floor(30000 / names.length));
  let batch = [];
  let copied = 0;

  async function flush() {
    if (!batch.length) return;
    const values = [];
    const tuples = batch.map((row, rowIndex) => {
      const placeholders = names.map((name, columnIndex) => {
        values.push(row[name]);
        return `$${rowIndex * names.length + columnIndex + 1}`;
      });
      return `(${placeholders.join(', ')})`;
    });
    await client.query(
      `INSERT INTO ${quoteIdentifier(tableName)} (${names.map(quoteIdentifier).join(', ')}) VALUES ${tuples.join(', ')}`,
      values
    );
    copied += batch.length;
    batch = [];
  }

  for (const row of statement.iterate()) {
    batch.push(row);
    if (batch.length >= batchSize) await flush();
  }
  await flush();
  return copied;
}

async function recreateForeignKeys(client, sqlite, tables) {
  const tableSet = new Set(tables.map((table) => table.name.toLowerCase()));
  for (const table of tables) {
    const keys = sqlite.prepare(`PRAGMA foreign_key_list(${quoteIdentifier(table.name)})`).all();
    for (const key of keys) {
      if (!tableSet.has(String(key.table).toLowerCase())) continue;
      const constraint = `fk_${table.name}_${key.id}_${key.seq}`;
      const onDelete = /^(CASCADE|RESTRICT|SET NULL|SET DEFAULT|NO ACTION)$/i.test(key.on_delete) ? key.on_delete : 'NO ACTION';
      const onUpdate = /^(CASCADE|RESTRICT|SET NULL|SET DEFAULT|NO ACTION)$/i.test(key.on_update) ? key.on_update : 'NO ACTION';
      await client.query(`
        ALTER TABLE ${quoteIdentifier(table.name)}
        ADD CONSTRAINT ${quoteIdentifier(constraint)}
        FOREIGN KEY (${quoteIdentifier(key.from)}) REFERENCES ${quoteIdentifier(key.table)} (${quoteIdentifier(key.to)})
        ON UPDATE ${onUpdate} ON DELETE ${onDelete}
      `);
    }
  }
}

async function recreateIndexes(client, sqlite, tables) {
  for (const table of tables) {
    const indexes = sqlite.prepare(`PRAGMA index_list(${quoteIdentifier(table.name)})`).all();
    for (const index of indexes) {
      if (String(index.origin).toLowerCase() === 'pk') continue;
      const columns = sqlite.prepare(`PRAGMA index_info(${quoteIdentifier(index.name)})`).all();
      if (!columns.length || columns.some((column) => !column.name)) {
        console.warn(`Skipped unsupported expression index: ${index.name}`);
        continue;
      }
      await client.query(
        `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${quoteIdentifier(index.name)} ON ${quoteIdentifier(table.name)} (${columns.map((column) => quoteIdentifier(column.name)).join(', ')})`
      );
    }
  }
}

async function resetIdentity(client, tableName, columns) {
  const identity = columns.find((column) => column.pk && postgresType(column.type) === 'BIGINT');
  if (!identity) return;
  const sequence = await client.query('SELECT pg_get_serial_sequence($1, $2) AS name', [tableName.toLowerCase(), identity.name.toLowerCase()]);
  if (!sequence.rows[0]?.name) return;
  const maximum = await client.query(`SELECT MAX(${quoteIdentifier(identity.name)}) AS value FROM ${quoteIdentifier(tableName)}`);
  const value = maximum.rows[0]?.value;
  await client.query('SELECT setval($1, $2, $3)', [sequence.rows[0].name, value || 1, value !== null]);
}

async function run() {
  const sqlitePath = resolveSqlitePath();
  const config = createPostgresConfig();
  validatePostgresConfig(config);
  const sqlite = new Database(sqlitePath, { readonly: true, fileMustExist: true });
  const pool = new Pool(config);
  const client = await pool.connect();

  try {
    const integrity = sqlite.pragma('quick_check');
    if (integrity.length !== 1 || String(integrity[0].quick_check).toLowerCase() !== 'ok') {
      throw new Error('SQLite quick_check failed; migration was cancelled.');
    }

    const tables = sqlite.prepare("SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
    const views = sqlite.prepare("SELECT name, sql FROM sqlite_master WHERE type = 'view' ORDER BY name").all();
    const translatedViews = views.map((view) => {
      const body = String(view.sql || '').replace(/^\s*CREATE\s+VIEW\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:"[^"]+"|\S+)\s+AS\s+/i, '');
      const sql = translatePostgresSql(body);
      if (/\b(?:strftime|ifnull|date)\s*\(/i.test(sql)) {
        throw new Error(`View ${view.name} still contains unsupported SQLite functions after translation.`);
      }
      return { ...view, translatedSql: sql };
    });
    const existing = [];
    for (const table of tables) {
      if (await targetTableExists(client, table.name)) existing.push(table.name);
    }
    if (existing.length && !force) {
      throw new Error(`Target PostgreSQL tables already exist: ${existing.join(', ')}. Re-run with --force to replace them.`);
    }

    await client.query('BEGIN');
    for (const view of [...views].reverse()) {
      await client.query(`DROP VIEW IF EXISTS ${quoteIdentifier(view.name)} CASCADE`);
    }
    for (const table of [...tables].reverse()) {
      await client.query(`DROP TABLE IF EXISTS ${quoteIdentifier(table.name)} CASCADE`);
    }
    await client.query('DROP TABLE IF EXISTS app_column_keys');
    await client.query(`
      CREATE TABLE app_column_keys (
        table_name TEXT NOT NULL,
        column_name TEXT NOT NULL,
        js_key TEXT NOT NULL,
        PRIMARY KEY (table_name, column_name)
      )
    `);

    const definitions = new Map();
    let totalRows = 0;
    for (const table of tables) {
      const definition = tableDefinition(sqlite, table.name);
      definitions.set(table.name, definition);
      await client.query(definition.sql);
      for (const column of definition.columns) {
        await client.query(
          'INSERT INTO app_column_keys (table_name, column_name, js_key) VALUES ($1, $2, $3)',
          [table.name.toLowerCase(), column.name.toLowerCase(), column.name]
        );
      }
      const copied = await copyTable(client, sqlite, table.name, definition.columns);
      totalRows += copied;
      console.log(`Migrated ${table.name}: ${copied} rows`);
    }

    await recreateForeignKeys(client, sqlite, tables);
    await recreateIndexes(client, sqlite, tables);
    for (const table of tables) {
      await resetIdentity(client, table.name, definitions.get(table.name).columns);
    }
    for (const view of translatedViews) {
      await client.query(`CREATE VIEW ${quoteIdentifier(view.name)} AS ${view.translatedSql}`);
      const columns = sqlite.prepare(`PRAGMA table_info(${quoteIdentifier(view.name)})`).all();
      for (const column of columns) {
        await client.query(
          'INSERT INTO app_column_keys (table_name, column_name, js_key) VALUES ($1, $2, $3)',
          [view.name.toLowerCase(), column.name.toLowerCase(), column.name]
        );
      }
    }

    await client.query('COMMIT');
    console.log(`Migration completed transactionally: ${tables.length} tables, ${views.length} views, ${totalRows} rows.`);
  } catch (error) {
    await client.query('ROLLBACK').catch(() => {});
    throw error;
  } finally {
    sqlite.close();
    client.release();
    await pool.end();
  }
}

if (require.main === module) {
  run().catch((error) => {
    console.error(`Migration failed: ${error.message}`);
    process.exitCode = 1;
  });
}

module.exports = {
  columnType,
  postgresType,
  tableDefinition
};