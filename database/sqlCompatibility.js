'use strict';

function replaceQuestionPlaceholders(sql) {
  let output = '';
  let parameterIndex = 0;
  let state = 'code';

  for (let index = 0; index < sql.length; index += 1) {
    const character = sql[index];
    const next = sql[index + 1];

    if (state === 'code') {
      if (character === "'") state = 'single';
      else if (character === '"') state = 'double';
      else if (character === '-' && next === '-') state = 'line-comment';
      else if (character === '/' && next === '*') state = 'block-comment';
      else if (character === '?') {
        parameterIndex += 1;
        output += `$${parameterIndex}`;
        continue;
      }
    } else if (state === 'single' && character === "'") {
      if (next === "'") {
        output += character + next;
        index += 1;
        continue;
      }
      state = 'code';
    } else if (state === 'double' && character === '"') {
      if (next === '"') {
        output += character + next;
        index += 1;
        continue;
      }
      state = 'code';
    } else if (state === 'line-comment' && (character === '\n' || character === '\r')) {
      state = 'code';
    } else if (state === 'block-comment' && character === '*' && next === '/') {
      output += character + next;
      index += 1;
      state = 'code';
      continue;
    }

    output += character;
  }

  return output;
}

function translateSqliteMaster(sql) {
  if (!/\bsqlite_master\b/i.test(sql)) return sql;

  return sql
    .replace(/\bsqlite_master\b/gi, 'information_schema.tables')
    .replace(/\btype\s+IN\s*\(\s*'table'\s*,\s*'view'\s*\)/gi, "table_type IN ('BASE TABLE', 'VIEW')")
    .replace(/\btype\s*=\s*'table'/gi, "table_type = 'BASE TABLE'")
    .replace(/\btype\s*=\s*'view'/gi, "table_type = 'VIEW'")
    .replace(/\bname\b/gi, 'table_name')
    .replace(/\btable_name\s+NOT\s+LIKE\s+'sqlite_%'/gi, "table_schema = 'public'")
    .replace(/\bFROM information_schema\.tables\b/gi, "FROM information_schema.tables WHERE table_schema = 'public'")
    .replace(/WHERE table_schema = 'public'\s+WHERE/gi, "WHERE table_schema = 'public' AND");
}

function translatePostgresSql(sql) {
  let translated = replaceQuestionPlaceholders(String(sql));

  translated = translated
    .replace(/strftime\s*\(\s*'%Y'\s*,\s*date\s*\(\s*REPLACE\s*\(([^,]+),\s*'\/'\s*,\s*'-'\s*\)\s*\)\s*\)/gi, "TO_CHAR(TO_DATE($1, 'YYYY-MM-DD'), 'YYYY')")
    .replace(/strftime\s*\(\s*'%(Y|m|W)'\s*,\s*date\s*\(\s*'now'\s*\)\s*\)/gi, (_match, format) => `TO_CHAR(CURRENT_DATE, '${({ Y: 'YYYY', m: 'MM', W: 'IW' })[format]}')`)
    .replace(/strftime\s*\(\s*'%(Y|m|W)'\s*,\s*'now'\s*\)/gi, (_match, format) => `TO_CHAR(CURRENT_DATE, '${({ Y: 'YYYY', m: 'MM', W: 'IW' })[format]}')`)
    .replace(/strftime\s*\(\s*'%(Y|m|W)'\s*,\s*([A-Za-z_][A-Za-z0-9_.]*)\s*\)/gi, (_match, format, value) => `TO_CHAR(TO_DATE(LEFT(${value}::text, 10), 'YYYY-MM-DD'), '${({ Y: 'YYYY', m: 'MM', W: 'IW' })[format]}')`)
    .replace(/\b([A-Za-z_][A-Za-z0-9_]*)\.EmpID\s*=\s*([A-Za-z_][A-Za-z0-9_]*)\.ID\b/gi, '$1.EmpID = CAST($2.ID AS TEXT)')
    .replace(/\b([A-Za-z_][A-Za-z0-9_]*)\.ID\s*=\s*([A-Za-z_][A-Za-z0-9_]*)\.EmpID\b/gi, 'CAST($1.ID AS TEXT) = $2.EmpID')
    .replace(/\bIFNULL\s*\(/gi, 'COALESCE(')
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/gi, 'INSERT INTO')
    .replace(/([\w."()]+)\s*=\s*(\$\d+)\s+COLLATE\s+NOCASE/gi, 'LOWER($1) = LOWER($2::text)')
    .replace(/\s+COLLATE\s+NOCASE\b/gi, '')
    .replace(/\bdate\s*\(\s*'now'\s*,\s*'localtime'\s*,\s*'([+-]\d+) day'\s*\)/gi, "TO_CHAR(CURRENT_DATE + INTERVAL '$1 day', 'YYYY-MM-DD')")
    .replace(/\bdate\s*\(\s*'now'\s*,\s*'localtime'\s*\)/gi, "TO_CHAR(CURRENT_DATE, 'YYYY-MM-DD')")
    .replace(/\bdate\s*\(\s*'now'\s*\)/gi, 'CURRENT_DATE')
    .replace(/\bdate\s*\(\s*REPLACE\s*\(([^,]+),\s*'\/'\s*,\s*'-'\s*\)\s*\)/gi, "TO_DATE($1, 'YYYY-MM-DD')")
    .replace(/\bdate\s*\(\s*(\$\d+)\s*\)/gi, "TO_DATE($1::text, 'YYYY-MM-DD')")
    .replace(/\bdate\s*\(\s*([A-Za-z_][A-Za-z0-9_.]*)\s*\)/gi, "TO_DATE(LEFT($1::text, 10), 'YYYY-MM-DD')")
    .replace(/\bdatetime\s*\(\s*([A-Za-z_][A-Za-z0-9_.]*)\s*\)/gi, "TO_TIMESTAMP($1, 'YYYY-MM-DD HH24:MI:SS')")
    .replace(/strftime\s*\(\s*'%Y-%m'\s*,\s*'now'\s*\)/gi, "TO_CHAR(CURRENT_DATE, 'YYYY-MM')")
    .replace(/strftime\s*\(\s*'%Y-%m'\s*,\s*([^\)]+)\)/gi, "TO_CHAR(TO_DATE($1, 'YYYY-MM-DD'), 'YYYY-MM')")
    .replace(/"([A-Za-z_][A-Za-z0-9_]*)"/g, (_match, identifier) => `"${identifier.toLowerCase()}"`);

  translated = translateSqliteMaster(translated);

  if (/^\s*INSERT\s+OR\s+IGNORE\b/i.test(String(sql)) && !/\bON\s+CONFLICT\b/i.test(translated)) {
    translated = `${translated.replace(/;\s*$/, '')} ON CONFLICT DO NOTHING`;
  }

  return translated;
}

function restoreRowKeys(row, columnKeyMap = new Map()) {
  if (!row) return row;

  return Object.fromEntries(Object.entries(row).map(([key, value]) => [columnKeyMap.get(key.toLowerCase()) || key, value]));
}

module.exports = {
  replaceQuestionPlaceholders,
  restoreRowKeys,
  translatePostgresSql
};