const test = require('node:test');
const assert = require('node:assert/strict');
const {
  replaceQuestionPlaceholders,
  restoreRowKeys,
  translatePostgresSql
} = require('../database/sqlCompatibility');

test('numbers placeholders without changing quoted text or comments', () => {
  const sql = "SELECT '?', \"?\" FROM Main WHERE ID = ? -- ?\nAND Name = ? /* ? */";
  assert.equal(
    replaceQuestionPlaceholders(sql),
    "SELECT '?', \"?\" FROM Main WHERE ID = $1 -- ?\nAND Name = $2 /* ? */"
  );
});

test('translates compatibility expressions used by application queries', () => {
  const sql = "SELECT IFNULL(Name, '') FROM Login WHERE Username = ? COLLATE NOCASE";
  assert.equal(
    translatePostgresSql(sql),
    "SELECT COALESCE(Name, '') FROM Login WHERE LOWER(Username) = LOWER($1::text)"
  );
});

test('translates insert-or-ignore and SQLite identity syntax', () => {
  assert.match(
    translatePostgresSql('CREATE TABLE Test (ID INTEGER PRIMARY KEY AUTOINCREMENT)'),
    /INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/
  );
  assert.equal(
    translatePostgresSql('INSERT OR IGNORE INTO Test (Name) VALUES (?)'),
    'INSERT INTO Test (Name) VALUES ($1) ON CONFLICT DO NOTHING'
  );
});

test('restores expected JavaScript row key casing', () => {
  const map = new Map([['id', 'ID'], ['username', 'Username']]);
  assert.deepEqual(restoreRowKeys({ id: 4, username: 'admin', count: 1 }, map), {
    ID: 4,
    Username: 'admin',
    count: 1
  });
});

test('translates repository date expressions and lowercase physical identifiers', () => {
  assert.equal(
    translatePostgresSql(`SELECT date(REPLACE(Today, '/', '-')) FROM "Daily1" WHERE date(Today) = date(?)`),
    `SELECT TO_DATE(Today, 'YYYY-MM-DD') FROM "daily1" WHERE TO_DATE(LEFT(Today::text, 10), 'YYYY-MM-DD') = TO_DATE($1::text, 'YYYY-MM-DD')`
  );
  assert.equal(
    translatePostgresSql("SELECT date('now', 'localtime', '+3 day')"),
    "SELECT TO_CHAR(CURRENT_DATE + INTERVAL '+3 day', 'YYYY-MM-DD')"
  );
});

test('translates SQLite calendar expressions used by migrated views', () => {
  const translated = translatePostgresSql(`
    SELECT strftime('%Y', d.Today), strftime('%m', d.Today), strftime('%W', d.Today),
           strftime('%Y', 'now'), strftime('%m', date('now')), date('now')
    FROM DailyAll d
  `);

  assert.doesNotMatch(translated, /\b(?:strftime|date)\s*\(/i);
  assert.match(translated, /TO_CHAR\(CURRENT_DATE, 'YYYY'\)/);
  assert.match(translated, /TO_CHAR\(CURRENT_DATE, 'MM'\)/);
  assert.match(translated, /'IW'/);
});

test('casts mixed SQLite employee identifiers in PostgreSQL joins', () => {
  assert.equal(
    translatePostgresSql('SELECT * FROM DailyAll d JOIN Main m ON d.EmpID = m.ID'),
    'SELECT * FROM DailyAll d JOIN Main m ON d.EmpID = CAST(m.ID AS TEXT)'
  );
});